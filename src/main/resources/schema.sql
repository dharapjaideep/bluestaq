-- Owns the database schema; Hibernate only validates against it (ddl-auto=validate).
-- Runs on every startup, so every statement must be idempotent and non-destructive:
-- CREATE ... IF NOT EXISTS only, never DROP or TRUNCATE. Keep the SQL portable
-- (H2 now, PostgreSQL later). Every new entity gets its table added here first.

-- "user" is a reserved word in H2, hence the plural name. Matches com.bluestaq.demo.model.User.
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255)             NOT NULL,
    password_hash VARCHAR(255)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Case-insensitive uniqueness relies on emails being stored lower-case (User.normalizeEmail).
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- A group of users who share notes. Matches com.bluestaq.demo.model.Team.
CREATE TABLE IF NOT EXISTS teams (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100)             NOT NULL,
    created_by BIGINT                   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_teams_created_by FOREIGN KEY (created_by) REFERENCES users (id)
);

-- Team membership (join table of Team.members). The composite key stops duplicate memberships.
CREATE TABLE IF NOT EXISTS team_members (
    team_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT pk_team_members PRIMARY KEY (team_id, user_id),
    CONSTRAINT fk_team_members_team FOREIGN KEY (team_id) REFERENCES teams (id),
    CONSTRAINT fk_team_members_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- "Which teams am I in?" is asked on every note access check; the PK only covers team_id first.
CREATE INDEX IF NOT EXISTS idx_team_members_user ON team_members (user_id);

-- A note, owned by one user. team_id NULL = personal note. Matches com.bluestaq.demo.model.Note.
-- content is VARCHAR rather than TEXT/CLOB so the same DDL and String mapping work on H2 and
-- PostgreSQL; the 20000 limit is also enforced by NoteRequest validation.
CREATE TABLE IF NOT EXISTS notes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(255)             NOT NULL,
    content    VARCHAR(20000),
    owner_id   BIGINT                   NOT NULL,
    team_id    BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notes_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_notes_team FOREIGN KEY (team_id) REFERENCES teams (id)
);

CREATE INDEX IF NOT EXISTS idx_notes_owner ON notes (owner_id);
CREATE INDEX IF NOT EXISTS idx_notes_team ON notes (team_id);
